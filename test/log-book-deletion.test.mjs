import test from 'node:test';
import assert from 'node:assert/strict';
import express from 'express';
import {PGlite} from '@electric-sql/pglite';
import {LOG_BOOK_SCHEMA,registerLogBooks} from '../log-book.mjs';
import {DELETION_PHONE} from '../log-book-deletion.mjs';

test('bulk deletion requires exact approval and delivered WhatsApp OTP, is atomic, scoped and recoverable',async t=>{
 const db=new PGlite();t.after(()=>db.close());await db.exec(LOG_BOOK_SCHEMA);
 const query=(sql,args)=>sql.includes('pg_advisory_xact_lock')?Promise.resolve({rows:[]}):!args&&sql.includes(';')?db.exec(sql):db.query(sql,args);
 const pool={query,connect:async()=>({query,release(){}})};
 const sent=[];let available=true;
 const app=express();app.use(express.json());
 const requireSession=(req,res,next)=>{const auth=req.headers.authorization;if(!auth)return res.status(401).json({error:'Sign in'});req.session={login:auth,role:'super',permissions:{adminLevel:'Admin'}};next();};
 const requireAdministrator=(req,res,next)=>req.session.login==='normal'?res.status(403).json({error:'Admin only'}):next();
 registerLogBooks(app,{pool,requireSession,requireAdministrator,getSiteScope:async session=>session.login==='restricted'?{sites:['Jayant OC']}:{sites:null},sendDeletionOtp:async message=>{if(!available)throw Error('No WhatsApp');sent.push(message);return {sent:true,messageId:'test-message'};}});
 app.use((e,req,res,next)=>res.status(500).json({error:e.message}));
 const server=app.listen(0,'127.0.0.1');await new Promise(r=>server.on('listening',r));t.after(()=>{server.closeAllConnections();server.close();});
 const base=`http://127.0.0.1:${server.address().port}`;
 const call=async(path,body,auth='admin',method=body?'POST':'GET')=>{const r=await fetch(base+path,{method,headers:{...(auth?{Authorization:auth}:{}),'Content-Type':'application/json'},...(body?{body:JSON.stringify(body)}:{})});return {status:r.status,data:await r.json()};};
 const api=(path,body,auth)=>call('/api/log-book-deletions/'+path,body,auth);
 const seed=async(n,kind='vehicle',scanned=false)=>{const data={bookDate:'2026-10-28',location:'Sasti',door:'V-'+n,...(scanned?{scanCardId:'source-'+n}:{})};return (await db.query("INSERT INTO mis_log_books(book_no,book_type,book_date,site,asset_id,data,request_key,created_by) VALUES($1,$2,'2026-10-28','Sasti',1,$3,md5($1)::uuid,'fixture') RETURNING *",['BOOK-'+n,kind,JSON.stringify(data)])).rows[0];};
 const preview=async(records,auth='admin')=>{const r=await api('preview',{records:records.map(r=>({id:r.id,revision:r.revision})),reason:'Duplicate entries'},auth);assert.equal(r.status,200,JSON.stringify(r.data));return r.data;};
 const a=await seed(1),b=await seed(2,'equipment',true),c=await seed(3);
 assert.equal((await api('entries',undefined,'')).status,401);assert.equal((await api('entries',undefined,'normal')).status,403);
 assert.equal((await api('entries')).data.records.length,3);
 assert.equal((await api('entries',undefined,'restricted')).data.records.length,0);
 assert.equal((await api('preview',{records:[a],reason:'Test scope'},'restricted')).status,403);
 assert.equal((await api('preview',{records:[a],reason:''})).status,400);
 assert.equal((await api('preview',{records:[a,a],reason:'duplicate'})).status,400);
 assert.equal((await api('preview',{records:[{...a,revision:0}],reason:'duplicate'})).status,409);
 assert.equal((await call('/api/log-books/vehicle/'+a.id,{revision:1},'admin','DELETE')).status,403);
 let p=await preview([a,b]);
 assert.deepEqual(p.records.map(r=>String(r.id)),[String(a.id),String(b.id)]);assert.match(p.impact,/recovery/);
 assert.equal((await api(p.id+'/otp',{approval:'Approve these changes'})).status,400);
 assert.equal((await api(p.id+'/otp',{approval:p.approval},'other-admin')).status,409);
 assert.equal((await api(p.id+'/confirm',{approval:p.approval,otp:'123456'})).status,403);
 available=false;assert.equal((await api(p.id+'/otp',{approval:p.approval})).status,503);
 assert.equal((await api(p.id+'/confirm',{approval:p.approval,otp:'123456'})).status,403);
 assert.equal((await api('entries')).data.records.length,3);
 // Reset the test clock's request timestamp, without weakening runtime throttling.
 await db.query("UPDATE mis_log_book_deletions SET otp_requested_at=NOW()-INTERVAL '2 minutes'");available=true;
 p=await preview([a,b]);
 assert.equal((await api(p.id+'/otp',{approval:p.approval})).status,200);assert.equal(sent.at(-1).to,DELETION_PHONE);
 assert.equal((await api(p.id+'/otp',{approval:p.approval})).status,409);
 assert.ok(!JSON.stringify(p).includes(sent.at(-1).otp));
 const wrong=sent.at(-1).otp==='111111'?'222222':'111111';
 assert.equal((await api(p.id+'/confirm',{approval:p.approval,otp:wrong})).status,400);
 assert.equal((await db.query('SELECT attempts FROM mis_log_book_deletions WHERE id=$1',[p.id])).rows[0].attempts,1);
 // A concurrent edit invalidates the whole approved batch, including the other record.
 await db.query('UPDATE mis_log_books SET revision=2 WHERE id=$1',[b.id]);
 assert.equal((await api(p.id+'/confirm',{approval:p.approval,otp:sent.at(-1).otp})).status,409);
 assert.equal((await api('entries')).data.records.length,3);
 const updated={...b,revision:2};await db.query("UPDATE mis_log_book_deletions SET otp_requested_at=NOW()-INTERVAL '2 minutes'");
 p=await preview([a,updated]);assert.equal((await api(p.id+'/otp',{approval:p.approval})).status,200);
 const success=await api(p.id+'/confirm',{approval:p.approval,otp:sent.at(-1).otp,records:[c]});assert.equal(success.status,200);assert.equal(success.data.deleted,2);
 assert.deepEqual((await api('entries')).data.records.map(r=>String(r.id)),[String(c.id)]);
 assert.equal((await api(p.id+'/confirm',{approval:p.approval,otp:sent.at(-1).otp})).status,409);
 const retained=(await db.query('SELECT * FROM mis_log_books WHERE id=$1',[b.id])).rows[0];assert.ok(retained.deleted_at);assert.equal(retained.data.scanCardId,'source-2');
 assert.equal((await api('history',undefined,'restricted')).data.records.length,0);
 const h=(await api('history')).data.records;assert.equal(h.length,1);assert.equal(h[0].snapshot.length,2);assert.ok(h[0].approved_at);assert.ok(h[0].delivered_at);assert.equal(h[0].otp_hash,undefined);
 // Too many guesses, expiry, account binding and hourly throttling all fail closed.
 await db.query("UPDATE mis_log_book_deletions SET otp_requested_at=NOW()-INTERVAL '2 minutes'");p=await preview([c]);assert.equal((await api(p.id+'/otp',{approval:p.approval})).status,200);
 for(let i=0;i<5;i++)assert.equal((await api(p.id+'/confirm',{approval:p.approval,otp:'bad'})).status,400);
 assert.equal((await api(p.id+'/confirm',{approval:p.approval,otp:sent.at(-1).otp})).status,429);
 const limited=await preview([c]);assert.equal((await api(limited.id+'/otp',{approval:limited.approval})).status,429);
 await db.query("UPDATE mis_log_book_deletions SET expires_at=NOW()-INTERVAL '1 minute' WHERE id=$1",[p.id]);
 assert.equal((await api(p.id+'/confirm',{approval:p.approval,otp:sent.at(-1).otp})).status,409);
 assert.equal((await api('entries')).data.records.length,1);
});
